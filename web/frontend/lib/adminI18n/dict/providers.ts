export function taskTypeLabel(locale: AdminLocale, taskType: string): string {
  const key = `providers.routing.task.${taskType}`;
  const row = PROVIDERS_DICT[key];
  if (row) return row[locale] ?? row.en ?? taskType;
  return taskType;
}

export function circuitStateLabel(locale: AdminLocale, state: string): string {
  if (state === 'open') return PROVIDERS_DICT['providers.circuit.stateOpen'][locale] ?? 'OPEN';
  if (state === 'half_open') return PROVIDERS_DICT['providers.circuit.stateHalfOpen'][locale] ?? 'HALF_OPEN';
  return PROVIDERS_DICT['providers.circuit.stateClosed'][locale] ?? 'CLOSED';
}
