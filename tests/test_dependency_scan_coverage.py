def test_pins_with_extras_are_scanned(scan, tmp_path):
    write(tmp_path, {"requirements.txt": "uvicorn[standard]==0.30.6\n"
                                         'PyJWT[crypto] == 2.13.0 ; python_version >= "3.8"\n'
                                         "psycopg[binary,pool]==3.3.4\n"})
    packages, _ = scan.collect(tmp_path, respect_independent=False)
    assert packages == {("PyPI", "uvicorn", "0.30.6"), ("PyPI", "PyJWT", "2.13.0"),
                        ("PyPI", "psycopg", "3.3.4")}


def test_uv_cargo_and_pub_lockfiles_are_read(scan, tmp_path):
    if scan.tomllib is None:
        pytest.skip("no TOML parser on this interpreter")
    write(tmp_path, {"py/uv.lock": UV_LOCK, "rs/Cargo.lock": CARGO_LOCK, "dart/pubspec.lock": PUBSPEC_LOCK})
    packages, owners = scan.collect(tmp_path, respect_independent=False)
    assert packages == {("PyPI", "psycopg", "3.3.4"), ("crates.io", "sha2", "0.10.8"),
                        ("Pub", "archive", "4.0.9")}
    assert owners[("Pub", "archive", "4.0.9")] == {"dart"}


BROKEN = {
    "package-lock with a trailing comma": {
        "package-lock.json": '{"lockfileVersion": 3, "packages": {"node_modules/next": {"version": "15.5.4"},}}'},
    "package-lock that is not an object": {"package-lock.json": "[]"},
    "pin the parser cannot read": {"requirements.txt": "flask===2.0.1\n"},
    "uv.lock that is not TOML": {"uv.lock": 'version = 1\n[[package]\nname = "x"\n'},
    "uv.lock with an unknown source": {"uv.lock": '[[package]]\nname = "x"\nversion = "1"\nsource = { svn = "x" }\n'},
    "Cargo.lock with an unknown source": {"Cargo.lock": '[[package]]\nname = "x"\nversion = "1"\nsource = "svn+x"\n'},
    "pubspec.lock hosted package without a version": {
        "pubspec.lock": "packages:\n  archive:\n    dependency: transitive\n    source: hosted\n"},
    "pubspec.lock in another layout": {"pubspec.lock": "packages:\n  archive:\n    source hosted\n"},
}


@pytest.mark.parametrize("case", sorted(BROKEN))
def test_unreadable_manifest_fails_gate(scan, monkeypatch, tmp_path, capsys, case):
    if scan.tomllib is None and "lock" in case and ("uv" in case or "Cargo" in case):
        pytest.skip("no TOML parser on this interpreter")
    calls = osv(monkeypatch, batch={"results": [{}]})
    assert gate(scan, monkeypatch, write(tmp_path, BROKEN[case])) == 2
    assert "no manifests found" not in capsys.readouterr().out
    assert calls == []


def test_toml_lockfile_without_a_toml_parser_fails_gate(scan, monkeypatch, tmp_path):
    monkeypatch.setattr(scan, "tomllib", None)
    osv(monkeypatch, batch={"results": [{}]})
    assert gate(scan, monkeypatch, write(tmp_path, {"uv.lock": UV_LOCK})) == 2


def test_upstream_checkouts_are_skipped_only_on_a_bare_run(scan, tmp_path):
    write(tmp_path, {"hub/requirements.txt": "b==1.0\n",
                     "hub/.upstreams/runtime/requirements.txt": "a==1.0\n"})
    bare, _ = scan.collect(tmp_path, respect_independent=True)
    explicit, _ = scan.collect(tmp_path / "hub", respect_independent=False)
    assert bare == {("PyPI", "b", "1.0")}
    assert explicit == {("PyPI", "a", "1.0"), ("PyPI", "b", "1.0")}


def test_every_manifest_the_gates_scan_is_readable():
    """What CI and deploy_pingblip.sh actually scan must parse, or they go red for it."""
    root, pingblip = load("root"), load("pingblip")
    if root.tomllib is None:
        pytest.skip("no TOML parser on this interpreter")
    packages, _ = root.collect(REPO, respect_independent=True)
    assert {eco for eco, _, _ in packages} >= {"npm", "PyPI", "crates.io", "Pub"}
    pingblip.collect(REPO / "pingblip", respect_independent=False)


def test_pub_reader_agrees_with_a_yaml_parser():
    yaml = pytest.importorskip("yaml")
    scan = load("root")
    locks = [p for p in REPO.rglob("pubspec.lock")
             if not {"node_modules", ".claude"} & set(p.relative_to(REPO).parts)]
    assert locks
    for lock in locks:
        data = yaml.safe_load(lock.read_text())
        expected = {("Pub", name, str(meta["version"])) for name, meta in data["packages"].items()
                    if meta["source"] == "hosted"}
        assert scan.pub_packages(lock) == expected, lock


