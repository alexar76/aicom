# -- Parity: the copy deploy_pingblip.sh runs must not drift from the parent scanner.

LOCAL = {"SKIP_DIRS", "INDEPENDENT", "_unpublished_root_dirs"}


def definitions(path):
    out = {}
    for node in ast.parse(path.read_text()).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            out[node.name] = ast.dump(node)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            for target in node.targets if isinstance(node, ast.Assign) else [node.target]:
                if isinstance(target, ast.Name):
                    out[target.id] = ast.dump(node.value) if node.value else None
        elif isinstance(node, ast.Try):
            out["<optional imports>"] = ast.dump(node)
    return {k: v for k, v in out.items() if k not in LOCAL}


def test_pingblip_scanner_logic_matches_the_parent_scanner():
    root, pingblip = definitions(SCANNERS["root"]), definitions(SCANNERS["pingblip"])
    assert sorted(pingblip) == sorted(root)
    assert [name for name in root if root[name] != pingblip[name]] == []
