"""The dependency gates must fail closed on anything they cannot read or check.

Every behavioural test runs against both scanners: the parent tree's, and PingBlip's
own copy, which is the one deploy_pingblip.sh gates on. A parity test keeps the two
from drifting apart again. No test contacts OSV.
"""
import ast
import importlib.util
import io
import json
import urllib.error
import urllib.request
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
SCANNERS = {"root": REPO / "scripts" / "dependency_scan.py",
            "pingblip": REPO / "pingblip" / "scripts" / "dependency_scan.py"}


def load(which):
    spec = importlib.util.spec_from_file_location(f"dependency_scan_{which}", SCANNERS[which])
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(params=sorted(SCANNERS))
def scan(request):
    return load(request.param)


def write(root, files):
    for name, text in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text)
    return root


def osv(monkeypatch, batch=None, advisories=None):
    """Answer OSV from memory: batch=None means offline, a missing advisory is a 404."""
    calls = []

    def urlopen(req, timeout=None):
        calls.append(req)
        if isinstance(req, urllib.request.Request):
            if batch is None:
                raise urllib.error.URLError("offline")
            return io.BytesIO(json.dumps(batch).encode())
        vid = req.rsplit("/", 1)[-1]
        if vid not in (advisories or {}):
            raise urllib.error.HTTPError(req, 404, "not found", {}, None)
        return io.BytesIO(json.dumps(advisories[vid]).encode())

    monkeypatch.setattr(urllib.request, "urlopen", urlopen)
    return calls


def gate(scan, monkeypatch, tree, *extra):
    monkeypatch.setattr("sys.argv", ["dependency_scan.py", str(tree), *extra])
    return scan.main()


DJANGO = {"requirements.txt": "django==2.2.0\n"}
HIT = {"results": [{"vulns": [{"id": "GHSA-synthetic"}]}]}


