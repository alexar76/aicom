#!/usr/bin/env bash
# Build agents/warden-scan/handler.js: WARDEN's static scan (warden/src in this monorepo) bundled
# into one classic script for HESTIA's JavaScript sandbox (QuickJS for WASI, no Node).
#
#   ESBUILD=/path/to/esbuild scripts/build_warden_scan.sh
#
# node:crypto, Buffer and TextDecoder come from agents/warden-scan/src/node-shims.js. The output
# names the WARDEN version and the esbuild version it was built with; tests/test_warden_scan.py
# rebuilds it when an esbuild is at hand and fails if the committed file differs.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
agent="$here/agents/warden-scan"
warden="$here/../warden"
esbuild="${ESBUILD:-esbuild}"
out="${1:-$agent/handler.js}"
version="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["version"])' "$warden/package.json")"
tmp="$(mktemp -d)"
cd "$here"  # esbuild names modules relative to the working directory: keep it fixed
trap 'rm -rf "$tmp"' EXIT
"$esbuild" "$agent/src/entry.ts" --bundle --format=iife --global-name=handler --platform=neutral \
  --target=es2022 --charset=utf8 --legal-comments=none --log-level=warning \
  --alias:node:crypto="$agent/src/node-shims.js" --inject:"$agent/src/globals.js" \
  --define:WARDEN_VERSION="\"$version\"" --outfile="$tmp/bundle.js"
{
  echo "// warden.scan@v1 for HESTIA: @aimarket/warden $version static scan, bundled by esbuild $("$esbuild" --version)."
  echo "// Generated by hestia-agents/scripts/build_warden_scan.sh from warden/src; do not edit by hand."
  cat "$tmp/bundle.js"
} > "$out"
echo "$out: $(wc -c < "$out" | tr -d ' ') bytes, WARDEN $version"
